"""属性克制表（《数值设定.md》§2）。

行 = 攻击方属性，列 = 防御方属性。

七属性表与规划文档 §3.2 完全一致；追加内部属性 "无"（通用招式），
"无" 的整行整列恒为 1.0，且不出现在克制表界面。

本模块**不 import 任何 UI / 引擎模块**。
"""

from __future__ import annotations

#: 七种正式属性（《数值设定.md》§1.2 / §2），顺序与克制表一致
TYPES: tuple[str, ...] = ("火", "水", "草", "风", "光", "暗", "雷")

#: 内部属性：无属性通用招式，克制系数恒为 1.0
NEUTRAL_TYPE: str = "无"

#: 攻击方属性 -> 防御方属性 -> 克制系数（《数值设定.md》§2，8×8 全表）
TYPE_CHART: dict[str, dict[str, float]] = {
    "火": {"火": 1.0, "水": 0.5, "草": 2.0, "风": 1.0, "光": 1.0, "暗": 1.0, "雷": 1.0, "无": 1.0},
    "水": {"火": 2.0, "水": 1.0, "草": 0.5, "风": 1.0, "光": 1.0, "暗": 1.0, "雷": 1.0, "无": 1.0},
    "草": {"火": 0.5, "水": 2.0, "草": 1.0, "风": 1.0, "光": 1.0, "暗": 1.0, "雷": 1.0, "无": 1.0},
    "风": {"火": 1.0, "水": 1.0, "草": 2.0, "风": 1.0, "光": 1.0, "暗": 1.0, "雷": 0.5, "无": 1.0},
    "光": {"火": 1.0, "水": 1.0, "草": 1.0, "风": 1.0, "光": 0.5, "暗": 2.0, "雷": 1.0, "无": 1.0},
    "暗": {"火": 1.0, "水": 1.0, "草": 1.0, "风": 1.0, "光": 2.0, "暗": 0.5, "雷": 1.0, "无": 1.0},
    "雷": {"火": 1.0, "水": 2.0, "草": 1.0, "风": 0.5, "光": 1.0, "暗": 1.0, "雷": 1.0, "无": 1.0},
    "无": {"火": 1.0, "水": 1.0, "草": 1.0, "风": 1.0, "光": 1.0, "暗": 1.0, "雷": 1.0, "无": 1.0},
}


def multiplier(attack_type: str, defend_type: str) -> float:
    """取克制系数（攻击方属性 -> 防御方属性）。

    参数
    ----
    attack_type
        攻击方属性，"无" 亦可。
    defend_type
        防御方属性，"无" 亦可。

    异常
    ----
    KeyError
        属性名不在克制表内（拼写错误）。
    """
    try:
        row = TYPE_CHART[attack_type]
    except KeyError:
        raise KeyError(
            f"未知攻击属性 {attack_type!r}，可用：{sorted(TYPE_CHART)}"
        ) from None
    try:
        return row[defend_type]
    except KeyError:
        raise KeyError(
            f"未知防御属性 {defend_type!r}，可用：{sorted(row)}"
        ) from None


def is_type(name: str) -> bool:
    """属性名是否合法（含内部属性 "无"）。"""
    return name in TYPE_CHART
