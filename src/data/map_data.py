# ---------------------------------------------------------------- 查询 helper
def get_map(map_id: int) -> dict:
    """按 ID 取地图定义；不存在时抛 KeyError。"""
    try:
        return MAPS[map_id]
    except KeyError:
        raise KeyError(f"没有编号为 {map_id} 的地图，可用：{sorted(MAPS)}") from None


def is_walkable_tile(tile_id: int) -> bool:
    """图块 ID 是否可走。"""
    return tile_id in WALKABLE_TILES


def tile_at(map_id: int, x: int, y: int) -> int | None:
    """取 (x, y) 格的图块 ID；越界返回 None。"""
    m = get_map(map_id)
    if not (0 <= x < m["w"] and 0 <= y < m["h"]):
        return None
    return m["tiles"][y][x]


def is_walkable(map_id: int, x: int, y: int) -> bool:
    """(x, y) 格是否在地图内且可走。"""
    t = tile_at(map_id, x, y)
    return t is not None and is_walkable_tile(t)


def map_pixel_size(map_id: int) -> tuple[int, int]:
    """地图像素尺寸 (宽, 高)。"""
    m = get_map(map_id)
    return m["w"] * TILE_SIZE, m["h"] * TILE_SIZE


def portals_of(map_id: int) -> list[dict]:
    """某张地图的出入口列表（拷贝，调用方不要改原数据）。"""
    return [dict(p) for p in get_map(map_id)["portals"]]


def npcs_of(map_id: int) -> list[dict]:
    """某张地图的 NPC 列表（拷贝）。"""
    return [dict(n) for n in get_map(map_id)["npcs"]]
