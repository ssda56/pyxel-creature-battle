# ---------------------------------------------------------------- 查询 helper
def get_map(map_id: int) -> dict:
    """按 ID 取地图定义；不存在时抛 KeyError。"""
    try:
        return MAPS[map_id]
    except KeyError:
        raise KeyError(f"没有编号为 {map_id} 的地图，可用：{sorted(MAPS)}") from None


def is_walkable_tile(tile_id: int) -> bool:
    """图块 ID 是否可走。"""
    return tile_id in WALKABLE_TILES


def tile_at(map_id: int, x: int, y: int) -> int | None:
    """取 (x, y) 格的图块 ID；越界返回 None。"""
    m = get_map(map_id)
    if not (0 <= x < m["w"] and 0 <= y < m["h"]):
        return None
    return m["tiles"][y][x]


def is_walkable(map_id: int, x: int, y: int) -> bool:
    """(x, y) 格是否在地图内且可走。"""
    t = tile_at(map_id, x, y)
    return t is not None and is_walkable_tile(t)


def map_pixel_size(map_id: int) -> tuple[int, int]:
    """地图像素尺寸 (宽, 高)。"""
    m = get_map(map_id)
    return m["w"] * TILE_SIZE, m["h"] * TILE_SIZE


def portals_of(map_id: int) -> list[dict]:
    """某张地图的出入口列表（拷贝，调用方不要改原数据）。"""
    return [dict(p) for p in get_map(map_id)["portals"]]


def npcs_of(map_id: int) -> list[dict]:
    """某张地图的 NPC 列表（拷贝）。"""
    return [dict(n) for n in get_map(map_id)["npcs"]]


# ------------------------------------------------------- 明雷遇敌（§10.3/§10.4）
def spawn_points_of(map_id: int) -> list[tuple[int, int]]:
    """某张地图的刷怪点列表（拷贝）。

    每个点都是**可走格**（野外全部落在草丛上），互不重叠。
    没有遇敌表的地图返回空列表。
    """
    return [(int(x), int(y)) for x, y in (get_map(map_id).get("spawn_points") or [])]


def encounters_of(map_id: int) -> dict | None:
    """某张地图的遇敌表（拷贝）；没有遇敌表的地图返回 None。

    结构::

        {"max_alive": 4, "respawn_frames": 360,
         "move_min": 80, "move_max": 140,
         "table": [{"species_id": .., "level_min": .., "level_max": .., "weight": ..}]}
    """
    enc = get_map(map_id).get("encounters")
    if enc is None:
        return None
    out = dict(enc)
    out["table"] = [dict(row) for row in enc.get("table", [])]
    return out


def roll_wild(map_id: int, rng) -> tuple[int, int] | None:
    """按遇敌表抽一只野生精灵，返回 (species_id, level)。

    - 种族按 weight 加权随机（§10.4）；
    - 等级在 [level_min, level_max] 闭区间里均匀随机；
    - 该地图没有遇敌表时返回 None。

    参数
    ----
    map_id
        地图 ID。
    rng
        随机源：需要 random() 与 randint(a, b)
        （random.Random 或模块级 random 都行）。
    """
    enc = encounters_of(map_id)
    if not enc:
        return None
    table = enc.get("table") or []
    total = sum(int(row["weight"]) for row in table)
    if total <= 0:
        return None

    # 加权抽种族
    roll = rng.random() * total
    acc = 0
    picked = table[-1]
    for row in table:
        acc += int(row["weight"])
        if roll < acc:
            picked = row
            break

    level = rng.randint(int(picked["level_min"]), int(picked["level_max"]))
    return int(picked["species_id"]), int(level)
